/** Days 1–21 get 3 names, days 22–30 get 4 names: 63 + 36 = 99. */
export function namesForDay(day: number) {
  const d = Math.min(30, Math.max(1, day));
  const start = d <= 21 ? (d - 1) * 3 : 63 + (d - 22) * 4;
  const count = d <= 21 ? 3 : 4;
  return NAMES.slice(start, start + count).map((n, i) => ({ index: start + i + 1, translit: n[0], ar: n[1], en: n[2], bn: n[3] }));
}
